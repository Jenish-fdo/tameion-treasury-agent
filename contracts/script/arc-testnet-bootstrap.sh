#!/usr/bin/env bash
# ARC TESTNET ONLY. Deploys MandateRegistry and DecisionLog, creates two fresh testnet-only keys (demo owner, relayer/agent
# wallet), funds them from the deployer, and runs the read-only post-deploy checks.
#
# The keystore password is NEVER handled by this script: each signing step runs `--account arc-testnet-deployer`, so Foundry
# itself asks you for the password on the terminal (three times: deploy, fund owner, fund agent). Private keys the script
# creates are written only to backend/.env.arc-testnet (mode 600, git-ignored) and are never printed.
#
#   ./script/arc-testnet-bootstrap.sh
#
# Safe to re-run: if backend/.env.arc-testnet already exists it deploys nothing and only tops up balances.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
CONTRACTS="$(cd "$HERE/.." && pwd)"
REPO="$(cd "$CONTRACTS/.." && pwd)"
ENV_OUT="$REPO/backend/.env.arc-testnet"

export ARC_TESTNET_RPC="${ARC_TESTNET_RPC:-https://rpc.testnet.arc.io}"
ACCOUNT="arc-testnet-deployer"
DEPLOYER="0xe90E61708AE8d6647D987409eb2d649EFd1676b5"
OWNER_FUNDING="2ether"     # native USDC has 18 decimals; "ether" is just the 1e18 unit. Gas for the owner's transactions.
AGENT_FUNDING="15ether"    # the agent wallet pays the demo vendors and its own gas
FEES=(--gas-price 40gwei --priority-gas-price 1gwei)
cd "$CONTRACTS"

command -v arc-forge >/dev/null && command -v arc-cast >/dev/null || { echo "arc-forge / arc-cast not found on PATH"; exit 1; }
[ "$(arc-cast chain-id --rpc-url "$ARC_TESTNET_RPC")" = "5042002" ] || { echo "Not Arc testnet (chain ID is not 5042002). Stopping."; exit 1; }
echo "Deployer $DEPLOYER: $(arc-cast balance "$DEPLOYER" --ether --rpc-url "$ARC_TESTNET_RPC") USDC, nonce $(arc-cast nonce "$DEPLOYER" --rpc-url "$ARC_TESTNET_RPC")"

if [ -f "$ENV_OUT" ]; then
  echo "1/4 $ENV_OUT exists: skipping deploy and key creation (top-up only)."
  set -a; . "$ENV_OUT"; set +a
else
  echo "1/4 Deploying (two transactions, one at a time). Foundry will ask for the keystore password ..."
  arc-forge script script/DeployTreasury.s.sol:DeployTreasury \
    --rpc-url arc_testnet --account "$ACCOUNT" --sender "$DEPLOYER" \
    --network arc --with-gas-price 40gwei --priority-gas-price 1gwei --broadcast --slow

  RUN="$CONTRACTS/broadcast/DeployTreasury.s.sol/5042002/run-latest.json"
  read -r REGISTRY LOG SIGNER < <(python3 -I - "$RUN" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
a = {t["contractName"]: t["contractAddress"] for t in d["transactions"] if t.get("contractName")}
print(a["MandateRegistry"], a["DecisionLog"], d["transactions"][0]["transaction"]["from"])
PY
)
  [ "$(printf '%s' "$SIGNER" | tr 'A-F' 'a-f')" = "$(printf '%s' "$DEPLOYER" | tr 'A-F' 'a-f')" ] || echo "WARNING: the deploy was signed by $SIGNER, not $DEPLOYER"
  echo "    MandateRegistry $REGISTRY"; echo "    DecisionLog     $LOG"

  echo "2/4 Creating fresh testnet-only keys (demo owner, relayer/agent wallet) ..."
  newkey() { arc-cast wallet new --json | python3 -I -c 'import json,sys; d=json.load(sys.stdin); d=d.get("data", d) if isinstance(d,dict) else d; d=d[0] if isinstance(d,list) else d; print(d["address"], d["private_key"])'; }
  read -r OWNER_ADDR OWNER_KEY < <(newkey)
  read -r AGENT_ADDR AGENT_KEY < <(newkey)
  umask 077
  cat > "$ENV_OUT" <<EOF
# ARC TESTNET ONLY. Generated by contracts/script/arc-testnet-bootstrap.sh. Never commit. Never fund with real money.
ARC_NETWORK=testnet
MANDATE_REGISTRY_ADDRESS=$REGISTRY
DECISION_LOG_ADDRESS=$LOG
BUSINESS_OWNER_PRIVATE_KEYS=$OWNER_KEY
BACKEND_WALLET_PRIVATE_KEY=$AGENT_KEY
API_KEYS=$(openssl rand -hex 32)
DEMO_OWNER_ADDRESS=$OWNER_ADDR
DEMO_AGENT_ADDRESS=$AGENT_ADDR
EOF
  chmod 600 "$ENV_OUT"
  unset OWNER_KEY AGENT_KEY
  set -a; . "$ENV_OUT"; set +a
fi

echo "3/4 Funding from the deployer (only what is missing). Foundry asks for the password for each transfer ..."
fund() { # <address> <amount in ether units> <label>
  local have; have="$(arc-cast balance "$1" --ether --rpc-url "$ARC_TESTNET_RPC")"
  if python3 -I -c "import sys; sys.exit(0 if float(sys.argv[1]) >= float(sys.argv[2]) / 2 else 1)" "$have" "${2%ether}"; then
    echo "    $3 already holds $have USDC"; return
  fi
  arc-cast send "$1" --value "$2" --account "$ACCOUNT" --rpc-url "$ARC_TESTNET_RPC" "${FEES[@]}" >/dev/null
  echo "    $3 funded: $(arc-cast balance "$1" --ether --rpc-url "$ARC_TESTNET_RPC") USDC"
}
fund "$DEMO_OWNER_ADDRESS" "$OWNER_FUNDING" "demo owner $DEMO_OWNER_ADDRESS"
fund "$DEMO_AGENT_ADDRESS" "$AGENT_FUNDING" "agent wallet $DEMO_AGENT_ADDRESS"

echo "4/4 Read-only post-deploy checks ..."
RPC_URL="$ARC_TESTNET_RPC" CAST=arc-cast "$CONTRACTS/script/verify-deployment.sh" "$MANDATE_REGISTRY_ADDRESS" "$DECISION_LOG_ADDRESS"

echo "Done. Deployer left: $(arc-cast balance "$DEPLOYER" --ether --rpc-url "$ARC_TESTNET_RPC") USDC"
echo "Config for the demo: backend/.env.arc-testnet (keys inside; not printed, not committed)"
