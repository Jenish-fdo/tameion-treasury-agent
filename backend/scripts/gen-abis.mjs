#!/usr/bin/env node
// Regenerates src/chain/abis/*.ts from the compiled contracts, so the backend ABIs can never drift from the Solidity.
//   cd contracts && forge build && cd ../backend && node scripts/gen-abis.mjs
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const contracts = path.resolve(here, '../../contracts');
const outDir = path.resolve(here, '../src/chain/abis');
const forge = process.env.FORGE_BIN || 'forge';
mkdirSync(outDir, { recursive: true });

for (const [name, file] of [['MandateRegistry', 'mandateRegistry'], ['DecisionLog', 'decisionLog']]) {
  const json = execFileSync(forge, ['inspect', name, 'abi', '--json'], { cwd: contracts, encoding: 'utf8' });
  const abi = JSON.stringify(JSON.parse(json), null, 2);
  const exportName = `${file}Abi`;
  writeFileSync(
    path.join(outDir, `${file}.ts`),
    `// GENERATED by scripts/gen-abis.mjs from contracts/src/${name}.sol. Do not edit by hand.\nexport const ${exportName} = ${abi} as const;\n`,
  );
  console.log(`wrote src/chain/abis/${file}.ts`);
}
